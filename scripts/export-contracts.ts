import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

// Find forge binary
function getForgeCmd(): string {
  const customPath = path.join(os.homedir(), '.foundry', 'bin', process.platform === 'win32' ? 'forge.exe' : 'forge');
  if (fs.existsSync(customPath)) {
    return `"${customPath}"`;
  }
  return 'forge';
}

console.log('Building contracts with Forge...');
const forgeCmd = getForgeCmd();
const contractsDir = path.join(rootDir, 'packages', 'contracts');
try {
  execSync(`${forgeCmd} build`, { cwd: contractsDir, stdio: 'inherit' });
} catch (e) {
  console.error('Failed to run forge build:', e);
  process.exit(1);
}

const factoryArtifactPath = path.join(
  rootDir,
  'packages/contracts/out/BallastFactory.sol/BallastFactory.json'
);
const vaultArtifactPath = path.join(
  rootDir,
  'packages/contracts/out/BallastVault.sol/BallastVault.json'
);

if (!fs.existsSync(factoryArtifactPath) || !fs.existsSync(vaultArtifactPath)) {
  console.error('Artifacts not found! Forge build may have failed.');
  process.exit(1);
}

const factoryArtifact = JSON.parse(fs.readFileSync(factoryArtifactPath, 'utf-8'));
const vaultArtifact = JSON.parse(fs.readFileSync(vaultArtifactPath, 'utf-8'));

const factoryAbi = factoryArtifact.abi;
const vaultAbi = vaultArtifact.abi;

const sharedAbisDir = path.join(rootDir, 'packages/shared/abis');
if (!fs.existsSync(sharedAbisDir)) {
  fs.mkdirSync(sharedAbisDir, { recursive: true });
}

fs.writeFileSync(
  path.join(sharedAbisDir, 'BallastFactory.json'),
  JSON.stringify(factoryAbi, null, 2) + '\n'
);
fs.writeFileSync(
  path.join(sharedAbisDir, 'BallastVault.json'),
  JSON.stringify(vaultAbi, null, 2) + '\n'
);

console.log('✓ Exported ABI JSON files to packages/shared/abis/');

// Generate typed TypeScript constants with "as const"
const abisTsContent = `// Autogenerated by scripts/export-contracts.ts - DO NOT EDIT MANUALLY

export const BallastFactoryAbi = ${JSON.stringify(factoryAbi, null, 2)} as const;

export const BallastVaultAbi = ${JSON.stringify(vaultAbi, null, 2)} as const;

export type BallastFactoryAbiType = typeof BallastFactoryAbi;
export type BallastVaultAbiType = typeof BallastVaultAbi;
`;

const abisTsPath = path.join(rootDir, 'packages/shared/src/abis.ts');
fs.writeFileSync(abisTsPath, abisTsContent);

console.log('✓ Generated typed constants in packages/shared/src/abis.ts');
